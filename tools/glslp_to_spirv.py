"""Compiles single-pass RetroArch GLSL presets to SPIR-V for SDL's GPU renderer, as one C header.

    python3 tools/glslp_to_spirv.py --glslc PATH --out tlk_gpu_shaders.h PRESET.glslp...
    python3 tools/glslp_to_spirv.py --out tlk_gpu_shaders.h         # no glslc: a header with no presets

The desktop's OpenGL presenter reads the same presets at run time. Here each pass's fragment half is preprocessed
with FRAGMENT and PARAMETER_UNIFORM defined, then given SDL's binding layout: `Texture` at set 2 binding 0, every
other uniform in one std140 block at set 3 binding 0, `vTexCoord` at location 1 and `FragColor` at location 0.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

# std140 size and alignment of each type a preset's uniform may have, in bytes.
STD140 = {"float": (4, 4), "int": (4, 4), "vec2": (8, 8), "vec3": (12, 16), "vec4": (16, 16)}
_IN = re.compile(r"^[ \t]*(?:(?:smooth|flat|noperspective|centroid|lowp|mediump|highp)\s+)*in\s+(\w+)\s+(\w+)\s*;", re.M)
_OUT = re.compile(r"^[ \t]*(?:(?:lowp|mediump|highp)\s+)*out\s+(\w+)\s+(\w+)\s*;", re.M)
_PARAM = re.compile(r'^\s*#pragma\s+parameter\s+(\w+)\s+"([^"]*)"\s+(\S+)\s+(\S+)\s+(\S+)(?:\s+(\S+))?', re.M)
_UNIFORM = re.compile(r"\buniform\s+(?:(?:lowp|mediump|highp)\s+)?(\w+)\s+(\w+)\s*;")
_VERSION = re.compile(r"^\s*#version[^\n]*\n", re.M)


@dataclass
class Param:
    name: str
    label: str
    default: float
    min: float
    max: float
    step: float


@dataclass
class Preset:
    name: str
    filter_linear: bool
    pass_file: Path
    params: list[Param] = field(default_factory=list)
    uniforms: list[Uniform] = field(default_factory=list)
    size: int = 0
    spirv: bytes = b""


class PresetError(ValueError):
    """A preset this build can't compile for the GPU renderer, with the reason."""


@dataclass
class Uniform:
    name: str
    type: str
    offset: int


def c_header(presets: list[Preset]) -> str:
    out = ["/* Generated by tools/glslp_to_spirv.py. Do not edit. */",
           "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
           "typedef struct { const char *name; uint32_t offset, floats; int is_int; } TlkGpuUniform;",
           "typedef struct { const char *name, *label; float def, min, max, step; } TlkGpuParam;",
           "typedef struct {",
           "    const char *name;",
           "    int filter_linear;",
           "    const uint8_t *spirv;",
           "    size_t spirv_size;",
           "    const TlkGpuUniform *uniforms;",
           "    int uniform_count;",
           "    uint32_t uniform_size;",
           "    const TlkGpuParam *params;",
           "    int param_count;",
           "} TlkGpuPreset;", ""]
    for i, p in enumerate(presets):
        words = ", ".join(f"0x{b:02x}" for b in p.spirv)
        out.append(f"static const uint8_t kSpirv{i}[] = {{ {words} }};")
        rows = ", ".join(f'{{ "{u.name}", {u.offset}, {STD140[u.type][0] // 4}, {int(u.type == "int")} }}'
                         for u in p.uniforms)
        out.append(f"static const TlkGpuUniform kUniforms{i}[] = {{ {rows or '{ NULL, 0, 0, 0 }'} }};")
        rows = ", ".join(f'{{ "{q.name}", "{_c_string(q.label)}", {q.default!r}f, {q.min!r}f, {q.max!r}f, {q.step!r}f }}'
                         for q in p.params)
        out.append(f"static const TlkGpuParam kParams{i}[] = {{ {rows or '{ NULL, NULL, 0, 0, 0, 0 }'} }};")
    out.append("static const TlkGpuPreset kTlkGpuPresets[] = {")
    for i, p in enumerate(presets):
        out.append(f'    {{ "{p.name}", {int(p.filter_linear)}, kSpirv{i}, sizeof kSpirv{i}, kUniforms{i}, '
                   f"{len(p.uniforms)}, {p.size}, kParams{i}, {len(p.params)} }},")
    if not presets:
        out.append("    { NULL, 0, NULL, 0, NULL, 0, 0, NULL, 0 }")
    out += ["};", f"enum {{ kTlkGpuPresetCount = {len(presets)} }};", ""]
    return "\n".join(out)


def compile_preset(path: Path, glslc: str) -> Preset:
    preset = read_preset(path)
    src = preset.pass_file.read_text(encoding="utf-8")
    text = to_vulkan(preprocess(src, glslc), preset)
    with tempfile.TemporaryDirectory() as tmp:
        frag, spv = Path(tmp) / f"{preset.name}.frag", Path(tmp) / f"{preset.name}.spv"
        frag.write_text(text, encoding="utf-8")
        r = subprocess.run([glslc, "-fshader-stage=frag", "--target-env=vulkan1.0", "-O", "-o", str(spv), str(frag)],
                           capture_output=True, text=True, timeout=60)
        if r.returncode != 0:
            raise PresetError(f"{path.name}: glslc failed:\n{r.stderr}")
        preset.spirv = spv.read_bytes()
    return preset


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--glslc")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("presets", nargs="*", type=Path)
    args = ap.parse_args(argv)
    try:
        presets = [compile_preset(p, args.glslc) for p in args.presets] if args.glslc else []
    except PresetError as e:
        print(f"glslp_to_spirv: {e}", file=sys.stderr)
        return 1
    header = c_header(presets)
    # Rewriting an unchanged header would rebuild everything that includes it.
    if not args.out.exists() or args.out.read_text(encoding="utf-8") != header:
        args.out.write_text(header, encoding="utf-8")
    return 0


def parse_params(src: str) -> list[Param]:
    out = []
    for m in _PARAM.finditer(src):
        name, label, default, lo, hi, step = m.groups()
        out.append(Param(name, label, float(default), float(lo), float(hi), float(step or 0)))
    return out


def preprocess(src: str, glslc: str) -> str:
    """The fragment half of a pass, with the preprocessor run and the `#pragma parameter` lines kept."""
    params = "".join(m.group(0) + "\n" for m in _PARAM.finditer(src))
    body = _PARAM.sub("", _VERSION.sub("", src))
    r = subprocess.run([glslc, "-E", "-fshader-stage=frag", "-"],
                       input="#version 450\n#define FRAGMENT\n#define PARAMETER_UNIFORM\n" + body,
                       capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise PresetError(f"preprocessing failed:\n{r.stderr}")
    return params + r.stdout


def read_preset(path: Path) -> Preset:
    keys = _preset_keys(path)
    if keys.get("shaders", "1") != "1":
        raise PresetError(f"{path.name}: {keys['shaders']} passes; the GPU renderer takes single-pass presets only")
    if "shader0" not in keys:
        raise PresetError(f"{path.name}: no shader0")
    linear = keys.get("filter_linear0", "false").lower() in ("true", "1")
    return Preset(path.stem, linear, path.parent / keys["shader0"])


def to_vulkan(text: str, preset: Preset) -> str:
    """Rewrites a preprocessed fragment pass to SDL's GPU binding layout, filling the preset's uniforms and params."""
    preset.params = parse_params(text)
    text = _PARAM.sub("", text)
    for m in _IN.finditer(text):
        if m.group(2) != "vTexCoord":
            raise PresetError(f"{preset.name}: reads `{m.group(2)}`; this tool connects vTexCoord only")
    for m in _OUT.finditer(text):
        if m.group(2) != "FragColor":
            raise PresetError(f"{preset.name}: writes `{m.group(2)}`; only FragColor goes to the screen")
    text = _IN.sub("layout(location = 1) in vec2 vTexCoord;", text)
    text = _OUT.sub("layout(location = 0) out vec4 FragColor;", text)
    offset = 0
    for m in _UNIFORM.finditer(text):
        kind, name = m.groups()
        if name == "Texture" and kind == "sampler2D":
            continue
        if kind not in STD140:
            raise PresetError(f"{preset.name}: uniform `{kind} {name}`; a preset may read the game's Texture and "
                             f"float, int or vecN uniforms only")
        size, align = STD140[kind]
        offset = (offset + align - 1) // align * align
        preset.uniforms.append(Uniform(name, kind, offset))
        offset += size
    preset.size = (offset + 15) // 16 * 16
    text = _UNIFORM.sub(lambda m: "layout(set = 2, binding = 0) uniform sampler2D Texture;"
                        if m.group(2) == "Texture" else "", text)
    block = ""
    if preset.uniforms:
        members = "".join(f"    {u.type} {u.name};\n" for u in preset.uniforms)
        block = f"layout(set = 3, binding = 0, std140) uniform TlkUniforms {{\n{members}}};\n"
    version = _VERSION.search(text)
    head = text[:version.end()] if version else "#version 450\n"
    rest = text[version.end():] if version else text
    return head + block + rest


def _c_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _preset_keys(path: Path) -> dict[str, str]:
    keys = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            keys[k.strip()] = v.strip().strip('"')
    return keys


if __name__ == "__main__":
    sys.exit(main())
